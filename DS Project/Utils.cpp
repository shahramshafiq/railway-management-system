int displayWidth(const char* text) {
    int width = 0;
    int pos = 0;
    while (text[pos]) {
        unsigned char byte = (unsigned char)text[pos];
        if (byte < 128) {
            width++;
            pos++;
        } else if (byte < 192) {
            pos++;
        } else if (byte < 224) {
            width++;
            pos += 2;
        } else if (byte < 240) {
            width++;
            pos += 3;
        } else {
            width++;
            pos += 4;
        }
    }
    return width;
}
