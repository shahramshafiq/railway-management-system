bool isBlankString(const char* str) {
    if (!str || str[0] == '\0') {
        return true;
    }
    for (int i = 0; str[i] != '\0'; i++) {
        if (str[i] != ' ' && str[i] != '\t') {
            return false;
        }
    }
    return true;
}

