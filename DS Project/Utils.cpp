void getCurrentTimestamp(char* buffer, int maxLen) {
    time_t rawTime = time(nullptr);
    struct tm* timeInfo = localtime(&rawTime);
    snprintf(buffer, maxLen, "%04d-%02d-%02d %02d:%02d:%02d",
             timeInfo->tm_year + 1900, timeInfo->tm_mon + 1, timeInfo->tm_mday,
             timeInfo->tm_hour, timeInfo->tm_min, timeInfo->tm_sec);
}

void strCopyN(char* destination, const char* source, int maxLen) {
    for (int pos = 0; pos < maxLen; pos++) {
        destination[pos] = source[pos];
        if (source[pos] == '\0') {
            return;
        }
    }
    destination[maxLen - 1] = '\0';
}

bool strEquals(const char* first, const char* second) {
    int pos = 0;
    while (first[pos] != '\0' && second[pos] != '\0') {
        if (first[pos] != second[pos]) {
            return false;
        }
        pos++;
    }
    return first[pos] == second[pos];
}

bool strEqualsNoCase(const char* first, const char* second) {
    for (int pos = 0; ; pos++) {
        char charA = first[pos];
        char charB = second[pos];
        if (charA >= 'A' && charA <= 'Z') {
            charA += 32;
        }
        if (charB >= 'A' && charB <= 'Z') {
            charB += 32;
        }
        if (charA != charB) {
            return false;
        }
        if (charA == '\0') {
            return true;
        }
    }
}

